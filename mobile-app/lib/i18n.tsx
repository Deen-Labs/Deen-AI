const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: async () => {},
  isRTL: false,
  t: (key: string, fallback?: string) => fallback || key,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLangState] = useState<AppLanguage>('en');

  useEffect(() => {
    // Initial fetch
    getAppLanguage().then(setLangState);

    // Subscribe to external changes (e.g. settings or onboarding)
    const unsubscribe = subscribeToLanguageChanges((newLang) => {
      setLangState(newLang);
    });

    return () => {
      unsubscribe();
    };
  }, []);

  const setLanguage = async (newLang: AppLanguage) => {
    setLangState(newLang);
    await persistAppLanguage(newLang);
  };

  const isRTL = language === 'ur' || language === 'ar';

  const t = (key: string, fallback?: string): string => {
    const langDict = translations[language] || translations.en;
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    if (translations.en && translations.en[key]) {
      return translations.en[key];
    }
    return fallback !== undefined ? fallback : key;
  };

  const contextValue = useMemo(
    () => ({
      language,
      setLanguage,
      isRTL,
      t,
    }),
    [language]
  );

  return (
    <LanguageContext.Provider value={contextValue}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}

