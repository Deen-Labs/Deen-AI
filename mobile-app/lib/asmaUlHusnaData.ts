/**
 * Search 99 names of Allah by English transliteration, meaning or Arabic text.
 */
export function searchAsmaUlHusna(query: string): AsmaUlHusnaData[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return ASMA_UL_HUSNA;
  return ASMA_UL_HUSNA.filter(
    (item) =>
      item.transliteration.toLowerCase().includes(clean) ||
      item.meaning.toLowerCase().includes(clean) ||
      item.name.includes(clean) ||
      String(item.number) === clean
  );
}

/**
 * Get single name by number 1-99.
 */
export function getAsmaUlHusnaByNumber(number: number): AsmaUlHusnaData | undefined {
  return ASMA_UL_HUSNA.find((item) => item.number === number);
}
